// 立場の短縮表記。幅の限られる場所で使う。
//
// 使い先は「報告一覧PDFの立場列」と「報告一覧をスマホでカード表示したときの立場」の2つ。
// **同じ表記を2か所に書くと片方だけ直して食い違う**ため、ここにまとめて両方から読む。
// (元はpdfReports.tsの中だけにあった)
//
// 「正開」は「特開」と並んだときに対応が分かるようにした表記。以前は「開」だった。
const STATUS_SHORT: Record<string, string> = {
  伝道者: '伝',
  補助開拓者: '補',
  正規開拓者: '正開',
  特別開拓者: '特開',
  野外の宣教者: '野宣',
  不活発者: '不',
}

/** 短縮表記を返す。未知の立場はそのまま返す(名簿から消えた古い表記が報告に残っている場合など) */
export function shortStatus(status: string): string {
  return STATUS_SHORT[status] ?? status
}
